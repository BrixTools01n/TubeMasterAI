package com.example.model

enum class ToolOutputType {
    LIST,           // List of numbered items (titles, ideas, topics) with individual copy buttons
    TAGS,           // Hashtags, video tags, keywords with chip UI and copy-all
    SCRIPT,         // Structured script with Hook, Intro, Main Content, CTA sections
    TEXT,           // Single rich formatted block (description, bio, post, email pitch)
    STRATEGY,       // Multi-section strategic plan (content pillar, calendar, persona, growth roadmap)
    KEY_VALUE       // Analyzed scores, metrics, clusters, comparison tables
}
