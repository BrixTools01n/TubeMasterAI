    fun get(key: String, language: AppLanguage): String {
        val dictionary = when (language) {
            AppLanguage.ENGLISH -> en
            AppLanguage.HINDI -> hi
            AppLanguage.HINGLISH -> hinglish
        }
        val match = dictionary[key] ?: en[key]
        if (match != null) return match

        // Safe Fallback: Never ever show raw keys like "pricing.upgrade_cta" or "saved.empty_title"
        val lastSegment = key.substringAfterLast('.').replace('_', ' ')
        return lastSegment.replaceFirstChar { if (it.isLowerCase()) it.titlecase(Locale.US) else it.toString() }
    }
